// Generate from a verified PostgreSQL schema. DATABASE_URL is parsed into private libpq environment variables,
// never placed in process arguments or printed. Regenerate again after staging drift review.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { databaseEnv } from './database-env.mjs';
if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required');
const env = databaseEnv(process.env.DATABASE_URL);
const query = sql => JSON.parse(execFileSync('psql',['-X','-A','-t','-v','ON_ERROR_STOP=1','-c',sql],{env,encoding:'utf8'}).trim());
const columns = query(`SELECT coalesce(json_agg(x),'[]') FROM (
 SELECT c.relname AS table_name,a.attname AS name,format_type(a.atttypid,a.atttypmod) AS type,
 a.attnotnull AS required, d.oid IS NOT NULL AS has_default
 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_attribute a ON a.attrelid=c.oid
 LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
 WHERE n.nspname='public' AND c.relkind='r' AND a.attnum>0 AND NOT a.attisdropped ORDER BY c.relname,a.attnum) x`);
const functions = query(`SELECT coalesce(json_agg(x),'[]') FROM (
 SELECT p.proname AS name,p.proargnames AS names,p.pronargdefaults AS defaults,
 ARRAY(SELECT format_type(t,NULL) FROM unnest(p.proargtypes::oid[]) t) AS types,format_type(p.prorettype,NULL) AS returns
 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND p.prorettype<>'trigger'::regtype AND p.proname NOT LIKE 'pg_%'
 ORDER BY p.proname) x`);
const enums = query(`SELECT coalesce(json_agg(x),'[]') FROM (SELECT t.typname AS name,array_agg(e.enumlabel ORDER BY e.enumsortorder) AS values FROM pg_type t JOIN pg_enum e ON e.enumtypid=t.oid JOIN pg_namespace n ON n.oid=t.typnamespace WHERE n.nspname='public' GROUP BY t.typname) x`);
const relationships = query(`SELECT coalesce(json_agg(x),'[]') FROM (
 SELECT c.relname AS table_name,con.conname AS name,r.relname AS referenced,
 ARRAY(SELECT a.attname FROM unnest(con.conkey) WITH ORDINALITY k(num,pos) JOIN pg_attribute a ON a.attrelid=c.oid AND a.attnum=k.num ORDER BY k.pos) AS columns,
 ARRAY(SELECT a.attname FROM unnest(con.confkey) WITH ORDINALITY k(num,pos) JOIN pg_attribute a ON a.attrelid=r.oid AND a.attnum=k.num ORDER BY k.pos) AS referenced_columns
 FROM pg_constraint con JOIN pg_class c ON c.oid=con.conrelid JOIN pg_class r ON r.oid=con.confrelid JOIN pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname='public' AND con.contype='f') x`);
const mapped = type => {
 if(type.endsWith('[]'))return `${mapped(type.slice(0,-2))}[]`;
 if(enums.some(e=>e.name===type))return `Database['public']['Enums'][${JSON.stringify(type)}]`;
 if(/^(integer|bigint|smallint|numeric|real|double precision)/.test(type))return 'number';
 if(type==='boolean')return 'boolean';
 if(type==='jsonb'||type==='json')return 'Json';
 if(type==='void')return 'undefined';
 return 'string';
};
let output=`// Generated by scripts/generate-db-types.mjs from the verified local baseline + migrations.\n// This is not evidence of the live production schema. Do not edit manually.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = { public: { Tables: {\n`;
for(const table of [...new Set(columns.map(c=>c.table_name))]){
 output+=`${JSON.stringify(table)}: {\n`;
 for(const kind of ['Row','Insert','Update']){
  output+=`${kind}: {\n`;
  for(const c of columns.filter(c=>c.table_name===table))output+=`${JSON.stringify(c.name)}${kind==='Update'||kind==='Insert'&&(!c.required||c.has_default)?'?':''}: ${mapped(c.type)}${c.required?'':' | null'};\n`;
  output+='};\n';
 }
 output+='Relationships: [';
 for(const rel of relationships.filter(r=>r.table_name===table))output+=`{foreignKeyName:${JSON.stringify(rel.name)};columns:${JSON.stringify(rel.columns)};isOneToOne:false;referencedRelation:${JSON.stringify(rel.referenced)};referencedColumns:${JSON.stringify(rel.referenced_columns)}} ,`;
 output+='];\n};\n';
}
output+='}; Views: { [_ in never]: never }; Functions: {\n';
for(const f of functions){
 output+=`${JSON.stringify(f.name)}: {Args: {`;
 (f.names||[]).forEach((name,i)=>{output+=`${JSON.stringify(name)}${i>=f.types.length-f.defaults?'?':''}: ${mapped(f.types[i])};`;});
 output+=`}; Returns: ${mapped(f.returns)}};\n`;
}
output+='}; Enums: {\n';for(const e of enums)output+=`${JSON.stringify(e.name)}: ${e.values.map(v=>JSON.stringify(v)).join(' | ')};\n`;
output+='}; CompositeTypes: { [_ in never]: never } } };\n';
output+=`export type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];\nexport type TablesInsert<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Insert'];\nexport type TablesUpdate<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Update'];\nexport type Enums<T extends keyof Database['public']['Enums']> = Database['public']['Enums'][T];\n`;
writeFileSync('src/integrations/supabase/types.ts',output);
console.log('Generated public schema types.');
