UPDATE public.delivery_zones AS dz
SET
  name = canonical.name,
  fee_cents = canonical.fee_cents,
  is_active = true
FROM temp_canonical_delivery_zones AS canonical
WHERE public.normalize_delivery_zone_name(dz.name) = public.normalize_delivery_zone_name(canonical.name);

INSERT INTO public.delivery_zones (name, fee_cents, is_active)
SELECT canonical.name, canonical.fee_cents, true
FROM temp_canonical_delivery_zones AS canonical
WHERE NOT EXISTS (
  SELECT 1
  FROM public.delivery_zones AS dz
  WHERE public.normalize_delivery_zone_name(dz.name) = public.normalize_delivery_zone_name(canonical.name)
);

UPDATE public.delivery_zones AS dz
SET is_active = false
WHERE NOT EXISTS (
  SELECT 1
  FROM temp_canonical_delivery_zones AS canonical
  WHERE public.normalize_delivery_zone_name(dz.name) = public.normalize_delivery_zone_name(canonical.name)
);
