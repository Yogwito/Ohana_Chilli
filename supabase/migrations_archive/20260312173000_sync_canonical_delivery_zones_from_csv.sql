CREATE OR REPLACE FUNCTION public.normalize_delivery_zone_name(value text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT lower(
    regexp_replace(
      translate(trim(coalesce(value, '')), 'ÁÉÍÓÚáéíóúÑñÜü', 'AEIOUaeiouNnUu'),
      '\s+',
      ' ',
      'g'
    )
  );
$$;

